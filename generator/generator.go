// Package generator drives protoc-gen-go-lite. NewGenerator picks the
// registered features a run asks for, and Generate writes one .pb.go file per
// input file: the types from generator_base, then each feature's methods in
// turn. A feature registers itself with RegisterFeature from an init
// function, so linking its package is what makes it available.
//
// Each file gets methods only for the messages it declares. A field whose
// message comes from another file calls that message's generated methods, so
// every proto package a message reaches must also be generated by
// protoc-gen-go-lite.
package generator

import (
	"runtime/debug"

	"github.com/aperturerobotics/protobuf-go-lite/compiler/protogen"
	"github.com/aperturerobotics/protobuf-go-lite/internal/editionssupport"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"

	generator_base "github.com/aperturerobotics/protobuf-go-lite/generator/base"
)

// Generator writes the .pb.go files for one plugin run.
type Generator struct {
	plugin   *protogen.Plugin
	cfg      *Config
	features []Feature
	local    map[protoreflect.FullName]bool
}

// SupportedFeatures are the protoc plugin features the generator declares.
const SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL) |
	uint64(pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)

// NewGenerator returns a Generator for the named features, or "all" for every
// registered one. It fails on an unknown feature name, or when cfg.Registry
// is set without the size, marshal and unmarshal features the registry needs.
func NewGenerator(plugin *protogen.Plugin, featureNames []string, cfg *Config) (*Generator, error) {
	// Declare the proto syntaxes and editions the plugin accepts.
	plugin.SupportedFeatures = SupportedFeatures
	plugin.SupportedEditionsMinimum = editionssupport.Minimum
	plugin.SupportedEditionsMaximum = editionssupport.Maximum

	// Resolve the features and check that the registry has what it needs.
	features, err := findFeatures(featureNames)
	if err != nil {
		return nil, err
	}
	if cfg != nil && cfg.Registry {
		if err := validateRegistryFeatures(featureNames); err != nil {
			return nil, err
		}
	}

	// Note the proto packages this run generates.
	local := make(map[protoreflect.FullName]bool)
	for _, f := range plugin.Files {
		if f.Generate {
			local[f.Desc.Package()] = true
		}
	}

	return &Generator{
		plugin:   plugin,
		cfg:      cfg,
		features: features,
		local:    local,
	}, nil
}

// Generate writes one .pb.go file for each file protoc asked to generate. An
// edition the generator does not support is reported on the plugin and skips
// that file.
func (gen *Generator) Generate() {
	for _, file := range gen.plugin.Files {
		if !file.Generate {
			continue
		}
		if err := validateEditionFile(file); err != nil {
			gen.plugin.Error(err)
			continue
		}

		importPath := file.GoImportPath
		gf := gen.plugin.NewGeneratedFile(file.GeneratedFilenamePrefix+".pb.go", importPath)
		p := &GeneratedFile{
			GeneratedFile: gf,
			Config:        gen.cfg,
			LocalPackages: gen.local,
		}

		// Generate header
		gen.generateHeader(p, file)

		// Generate base protobuf adapted from protobuf-go
		generator_base.GenerateFile(gen.plugin, file, gf, gen.cfg.Registry)

		// Generate vtproto features
		gen.generateFile(p, file)

		if gen.cfg.Registry {
			gen.generateRegistry(p, file)
		}
	}
}

// generateHeader writes the build tag, the generated-code notice, the source
// path and the package clause with its doc.
func (gen *Generator) generateHeader(p *GeneratedFile, file *protogen.File) {
	// Write the build constraint and the generated-code notice.
	if p.Config.BuildTag != "" {
		p.P("//go:build ", p.Config.BuildTag)
	}
	p.P("// Code generated by protoc-gen-go-lite. DO NOT EDIT.")
	if bi, ok := debug.ReadBuildInfo(); ok {
		p.P("// protoc-gen-go-lite version: ", bi.Main.Version)
	}
	if file.Proto.GetOptions().GetDeprecated() {
		p.P("// ", file.Desc.Path(), " is a deprecated file.")
	}
	p.P("// source: ", file.Desc.Path())
	p.P()
	p.P(generator_base.GenPackageKnownComment(file), "package ", file.GoPackageName)
	p.P()
}

func (gen *Generator) generateFile(p *GeneratedFile, file *protogen.File) {
	for _, feat := range gen.features {
		featGenerator := feat(p)
		_ = featGenerator.GenerateFile(file)
	}
}
